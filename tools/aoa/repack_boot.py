#!/usr/bin/env python3
"""Repack a Galaxy Y v0 boot image without extracting or changing cpio metadata."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
import struct

PARTITION_SIZE = 5 * 1024 * 1024

def align(n, page):
    return (n + page - 1) // page * page

def parse_boot(data):
    if data[:8] != b'ANDROID!':
        raise ValueError('Expected Android v0 boot image')
    values = struct.unpack_from('<10I', data, 8)
    ks, _, rs, _, ss, _, _, page, dt, version = values
    if page != 4096 or dt or version:
        raise ValueError('Expected Galaxy Y v0 header, 4096-byte pages, no DT')
    ko = page
    ro = ko + align(ks, page)
    so = ro + align(rs, page)
    end = so + align(ss, page)
    if end > len(data) or end > PARTITION_SIZE:
        raise ValueError('Truncated or oversized boot image')
    return data[:page], data[ko:ko+ks], data[ro:ro+rs], data[so:so+ss]

def parse_cpio(data):
    entries = []
    pos = 0
    while pos + 110 <= len(data):
        if data[pos:pos+6] not in (b'070701', b'070702'):
            raise ValueError('Expected newc cpio archive')
        values = [int(data[pos+6+i*8:pos+14+i*8], 16) for i in range(13)]
        size, namesize = values[6], values[11]
        name = data[pos+110:pos+110+namesize-1].decode()
        start = align(pos+110+namesize, 4)
        payload = data[start:start+size]
        entries.append((name, values, payload))
        pos = align(start+size, 4)
        if name == 'TRAILER!!!':
            return entries
    raise ValueError('Missing cpio trailer')

def pack_cpio(entries):
    out = bytearray()
    for name, old_values, data in entries:
        values = list(old_values)
        encoded = name.encode() + b'\0'
        values[6], values[11], values[12] = len(data), len(encoded), 0
        out += b'070701' + ''.join(f'{v:08x}' for v in values).encode() + encoded
        out += b'\0' * (align(len(out), 4) - len(out))
        out += data
        out += b'\0' * (align(len(out), 4) - len(out))
    out += b'\0' * (align(len(out), 512) - len(out))
    return bytes(out)

def usb_init():
    """The generic init.rc already owns none, adb and accessory[,adb]."""
    out = ['# Broadcom ICS USB frontend; generated by tools/aoa/repack_boot.py\n']
    modes = [('mass_storage', '04e8', '685b', False),
             ('mass_storage,adb', '04e8', '685e', True),
             ('adb,mass_storage', '04e8', '685e', True),
             ('rndis', '04e8', '6863', False),
             ('rndis,adb', '04e8', '6863', False)]
    for mode, vid, pid, adb in modes:
        out += [f'on property:sys.usb.config={mode}',
                '    write /sys/class/android_usb/android0/enable 0',
                f'    write /sys/class/android_usb/android0/idVendor {vid}',
                f'    write /sys/class/android_usb/android0/idProduct {pid}',
                f'    write /sys/class/android_usb/android0/functions {mode}',
                '    write /sys/class/android_usb/android0/enable 1']
        if adb:
            out += ['    start adbd']
        if mode.startswith('rndis'):
            out += ['    exec /system/bin/netcfg usb0 up']
        out += ['    setprop sys.usb.state $sys.usb.config', '']
    return ('\n'.join(out)+'\n').encode()

def repack(original, kernel):
    header, _, ramdisk, second = parse_boot(original)
    entries = parse_cpio(gzip.decompress(ramdisk))
    changed = []
    updated = []
    for name, values, payload in entries:
        new = payload
        if name == 'init.gt-s5360board.usb.rc':
            new = usb_init()
        elif name == 'init.rc':
            text = payload.decode()
            needle = 'on property:sys.usb.config=none\n    stop adbd\n'
            if text.count(needle) != 1:
                raise ValueError('Unexpected generic USB init handlers')
            text = text.replace(needle, needle+'    exec /system/bin/netcfg usb0 down\n')
            new = text.encode()
        if new != payload:
            changed.append(name)
        updated.append((name, values, new))
    if set(changed) != {'init.rc', 'init.gt-s5360board.usb.rc'}:
        raise ValueError(f'Unexpected ramdisk edits: {changed}')
    packed = pack_cpio(updated)
    # Verify every entry, including owners, modes, timestamps, symlinks and recovery.
    check = parse_cpio(packed)
    for (n, v, d), (n2, v2, d2) in zip(updated, check):
        assert n == n2 and d == d2
        assert all(v[i] == v2[i] for i in range(13) if i not in (6, 11, 12))
    ramdisk = gzip.compress(packed, compresslevel=9, mtime=0)
    page = len(header)
    header = bytearray(header)
    struct.pack_into('<I', header, 8, len(kernel))
    struct.pack_into('<I', header, 16, len(ramdisk))
    sha = hashlib.sha1()
    for payload in (kernel, ramdisk, second):
        sha.update(payload)
        sha.update(struct.pack('<I', len(payload)))
    header[576:608] = sha.digest() + b'\0'*12
    out = bytes(header)
    for payload in (kernel, ramdisk, second):
        out += payload + b'\0' * (align(len(payload), page) - len(payload))
    if len(out) > PARTITION_SIZE:
        raise ValueError(f'Boot image {len(out)} exceeds {PARTITION_SIZE}')
    new_header, new_kernel, new_ramdisk, new_second = parse_boot(out)
    assert new_kernel == kernel and new_second == second
    assert gzip.decompress(new_ramdisk) == packed
    for i, (a, b) in enumerate(zip(original[:page], new_header)):
        if not (8 <= i < 12 or 16 <= i < 20 or 576 <= i < 608):
            assert a == b, f'Unexpected header edit at {i}'
    return out, dict(bytes=len(out), spare_bytes=PARTITION_SIZE-len(out),
                     kernel_bytes=len(kernel), ramdisk_bytes=len(ramdisk),
                     changed_ramdisk_entries=changed,
                     sha256=hashlib.sha256(out).hexdigest())

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--original', type=Path, required=True)
    parser.add_argument('--kernel', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    image, report = repack(args.original.read_bytes(), args.kernel.read_bytes())
    args.output.write_bytes(image)
    print(json.dumps(report, indent=2))

if __name__ == '__main__':
    main()
